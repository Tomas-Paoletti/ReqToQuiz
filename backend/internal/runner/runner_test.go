// fakeEngine either fails or writes a quiz. calls counts Run invocations.
type fakeEngine struct {
	id        string
	fail      error
	quiz      func(req Request) *quiz.Quiz
	loggedOut bool
	calls     int
	fixes     []string
}

func (f *fakeEngine) ID() string   { return f.id }
func (f *fakeEngine) Name() string { return "Fake " + f.id }

func (f *fakeEngine) Auth(context.Context) AuthStatus {
	if f.loggedOut {
		return AuthStatus{State: AuthLoggedOut, LoginCommand: f.id + " login"}
	}
	return AuthStatus{State: AuthLoggedIn}
}

func (f *fakeEngine) Run(_ context.Context, req Request, _ string, progress Progress) (string, error) {
	f.calls++
	f.fixes = append(f.fixes, req.Fix)
	progress(StepGenerate, "generando")
	if f.fail != nil {
		return "", f.fail
	}
	data, _ := json.Marshal(f.quiz(req))
	return "s1", os.WriteFile(req.OutputPath, data, 0o644)
}

func goodQuiz(prefix string) func(Request) *quiz.Quiz {
	return func(req Request) *quiz.Quiz {
		q := &quiz.Quiz{Title: "T", Role: "R", Language: req.Language, Difficulty: req.Difficulty}
		topics := []string{"Docker", "PostgreSQL", "Kafka", "Kubernetes", "Redis", "gRPC", "OAuth", "Terraform", "Prometheus", "Nginx"}
		for i := 1; i <= req.Count; i++ {
			t := topics[(i-1)%len(topics)]
			q.Questions = append(q.Questions, quiz.Question{
				ID: i, Topic: t, Concept: fmt.Sprintf("%s %s concepto %c", prefix, t, 'a'+rune(i)),
				Question:    fmt.Sprintf("%s: ¿cómo se configura %s número %d en producción?", prefix, t, i),
				Options:     []string{"uno", "dos", "tres", "cuatro"},
				Answer:      i % 4,
				Explanation: "Explicación.",
			})
		}
		return q
	}
}

func newTestManager(t *testing.T, engines ...Engine) (*Manager, *store.Meta) {
	t.Helper()
	st, err := store.New(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	m := NewManager(t.TempDir(), engines, st)
	meta := &store.Meta{ID: store.NewID(), Count: 5, Language: "es", Difficulty: "mixed", Status: store.StatusGenerating, CreatedAt: time.Now()}
	if err := st.Create(meta, "input.md", []byte("Backend developer con Go y PostgreSQL")); err != nil {
		t.Fatal(err)
	}
	return m, meta
}

func runSync(t *testing.T, m *Manager, meta *store.Meta) []Event {
	t.Helper()
	job := m.Start(meta)
	_, ch, _ := job.Subscribe()
	for range ch {
	}
	history, _, _ := job.Subscribe()
	return history
}

func TestFallbackToCodexWhenClaudeFails(t *testing.T) {
	claude := &fakeEngine{id: "claude", fail: errors.New("Claude Code devolvió un error: Not logged in · Please run /login")}
	codex := &fakeEngine{id: "codex", quiz: goodQuiz("codex")}
	m, meta := newTestManager(t, claude, codex)

	events := runSync(t, m, meta)
	last := events[len(events)-1]
	if last.Type != "done" {
		t.Fatalf("expected done, got %+v", last)
	}
	sawFallback := false
	for _, e := range events {
		if strings.Contains(e.Message, "no pudo generar el quiz") && strings.Contains(e.Message, "Probando con Fake codex") {
			sawFallback = true
		}
	}
	if !sawFallback {
		t.Error("expected a progress message announcing the fallback")
	}
	got, _ := m.Store.Get(meta.ID)
	if got.Status != store.StatusReady || got.Engine != "codex" {
		t.Errorf("expected ready quiz generated by codex, got status=%s engine=%s", got.Status, got.Engine)
	}
	if claude.calls != 1 || codex.calls != 1 {
		t.Errorf("unexpected calls: claude=%d codex=%d", claude.calls, codex.calls)
	}
}

func TestNoFallbackWhenFirstEngineWorks(t *testing.T) {
	claude := &fakeEngine{id: "claude", quiz: goodQuiz("claude")}
	codex := &fakeEngine{id: "codex", quiz: goodQuiz("codex")}
	m, meta := newTestManager(t, claude, codex)

	runSync(t, m, meta)
	got, _ := m.Store.Get(meta.ID)
	if got.Engine != "claude" || codex.calls != 0 {
		t.Errorf("codex should not run: engine=%s codex calls=%d", got.Engine, codex.calls)
	}
}

func TestInvalidOutputIsRetriedThenFallsBack(t *testing.T) {
	bad := func(req Request) *quiz.Quiz { q := goodQuiz("x")(req); q.Questions = q.Questions[:2]; return q }
	claude := &fakeEngine{id: "claude", quiz: bad}
	codex := &fakeEngine{id: "codex", quiz: goodQuiz("codex")}
	m, meta := newTestManager(t, claude, codex)

	runSync(t, m, meta)
	if claude.calls != 2 {
		t.Fatalf("claude should be retried once, got %d calls", claude.calls)
	}
	if !strings.Contains(claude.fixes[1], "se esperaban exactamente 5 preguntas") {
		t.Errorf("retry should carry the validation error, got %q", claude.fixes[1])
	}
	if codex.fixes[0] != "" {
		t.Errorf("the fallback engine must start clean, got fix %q", codex.fixes[0])
	}
	got, _ := m.Store.Get(meta.ID)
	if got.Engine != "codex" || got.Status != store.StatusReady {
		t.Errorf("expected codex to generate it, got %+v", got)
	}
}

func TestAllEnginesFail(t *testing.T) {
	claude := &fakeEngine{id: "claude", fail: errors.New("límite de uso alcanzado")}
	codex := &fakeEngine{id: "codex", fail: errors.New("Codex no tiene sesión iniciada")}
	m, meta := newTestManager(t, claude, codex)

	events := runSync(t, m, meta)
	last := events[len(events)-1]
	if last.Type != "error" || !strings.Contains(last.Message, "límite de uso") || !strings.Contains(last.Message, "Codex no tiene sesión") {
		t.Fatalf("expected an error mentioning both engines, got %+v", last)
	}
	got, _ := m.Store.Get(meta.ID)
	if got.Status != store.StatusError {
		t.Errorf("expected error status, got %s", got.Status)
	}
}

func TestAutoSkipsEngineWithoutSession(t *testing.T) {
	claude := &fakeEngine{id: "claude", loggedOut: true, quiz: goodQuiz("claude")}
	codex := &fakeEngine{id: "codex", quiz: goodQuiz("codex")}
	m, meta := newTestManager(t, claude, codex)

	events := runSync(t, m, meta)
	if claude.calls != 0 {
		t.Errorf("an engine without session must not run, got %d calls", claude.calls)
	}
	skipped := false
	for _, e := range events {
		if strings.Contains(e.Message, "Fake claude no tiene sesión iniciada: ejecutá `claude login`") && strings.Contains(e.Message, "Se omite") {
			skipped = true
		}
	}
	if !skipped {
		t.Error("expected a progress message saying the engine was skipped")
	}
	if got, _ := m.Store.Get(meta.ID); got.Engine != "codex" || got.Status != store.StatusReady {
		t.Errorf("expected codex to generate it, got %+v", got)
	}
}

func TestChosenEngineIsUsedAlone(t *testing.T) {
	claude := &fakeEngine{id: "claude", quiz: goodQuiz("claude")}
	codex := &fakeEngine{id: "codex", quiz: goodQuiz("codex")}
	m, meta := newTestManager(t, claude, codex)
	meta.EngineChoice = "codex"

	runSync(t, m, meta)
	if claude.calls != 0 || codex.calls != 1 {
		t.Fatalf("only codex should run: claude=%d codex=%d", claude.calls, codex.calls)
	}
	if got, _ := m.Store.Get(meta.ID); got.Engine != "codex" {
		t.Errorf("expected engine codex, got %q", got.Engine)
	}
}

func TestChosenEngineDoesNotFallBack(t *testing.T) {
	claude := &fakeEngine{id: "claude", fail: errors.New("límite de uso alcanzado")}
	codex := &fakeEngine{id: "codex", quiz: goodQuiz("codex")}
	m, meta := newTestManager(t, claude, codex)
	meta.EngineChoice = "claude"

	events := runSync(t, m, meta)
	if codex.calls != 0 {
		t.Error("a chosen engine must not fall back to another one")
	}
	if last := events[len(events)-1]; last.Type != "error" || !strings.Contains(last.Message, "límite de uso") {
		t.Errorf("expected the chosen engine's error, got %+v", last)
	}
}

func TestCheckChoice(t *testing.T) {
	ctx := context.Background()
	in := &fakeEngine{id: "claude"}
	out := &fakeEngine{id: "codex", loggedOut: true}
	m, _ := newTestManager(t, in, out)

	if err := m.CheckChoice(ctx, "auto"); err != nil {
		t.Errorf("auto with one logged-in engine should pass: %v", err)
	}
	if err := m.CheckChoice(ctx, "claude"); err != nil {
		t.Errorf("logged-in engine should pass: %v", err)
	}
	if err := m.CheckChoice(ctx, "codex"); err == nil || !strings.Contains(err.Error(), "`codex login`") {
		t.Errorf("logged-out engine should fail with the login command, got %v", err)
	}
	if err := m.CheckChoice(ctx, "gemini"); err == nil {
		t.Error("unknown engine should fail")
	}

	only, _ := newTestManager(t, &fakeEngine{id: "claude", loggedOut: true})
	if err := only.CheckChoice(ctx, "auto"); err == nil {
		t.Error("auto with no logged-in engine should fail")
	}
	if err := only.CheckChoice(ctx, "codex"); err == nil || !strings.Contains(err.Error(), "no está instalado") {
		t.Errorf("missing engine should fail as not installed, got %v", err)
	}
	if len(only.Missing) != 1 || only.Missing[0] != "codex" {
		t.Errorf("expected codex reported as missing, got %v", only.Missing)
	}
}
